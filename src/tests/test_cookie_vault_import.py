from __future__ import annotations

import json

import pytest

from src.media.cookie_vault import CookieVault, CookieVaultError


def test_browser_json_cookie_export_is_scoped_and_encrypted(tmp_path):
    vault = CookieVault(str(tmp_path), "unit-test-key-that-is-not-a-real-secret-123")
    payload = json.dumps([
        {
            "domain": ".instagram.com",
            "expirationDate": 1825188022,
            "hostOnly": False,
            "httpOnly": True,
            "name": "sessionid",
            "path": "/",
            "secure": True,
            "session": False,
            "value": "fixture-session-value",
        },
        {
            "domain": ".instagram.com",
            "hostOnly": False,
            "httpOnly": False,
            "name": "csrftoken",
            "path": "/",
            "secure": True,
            "session": True,
            "value": "fixture-csrf-value",
        },
    ]).encode()

    vault.save("instagram", payload)
    output = tmp_path / "cookies.txt"
    assert vault.load_to_file("instagram", str(output)) is True
    text = output.read_text(encoding="utf-8")
    assert text.startswith("# Netscape HTTP Cookie File")
    assert "#HttpOnly_.instagram.com\tTRUE\t/\tTRUE\t1825188022\tsessionid\tfixture-session-value" in text
    assert ".instagram.com\tTRUE\t/\tTRUE\t0\tcsrftoken\tfixture-csrf-value" in text
    assert b"fixture-session-value" not in vault._path("instagram").read_bytes()


def test_cookie_import_rejects_domains_outside_selected_platform(tmp_path):
    vault = CookieVault(str(tmp_path), "unit-test-key-that-is-not-a-real-secret-123")
    payload = json.dumps([{
        "domain": ".evil.example",
        "name": "sessionid",
        "path": "/",
        "secure": True,
        "value": "fixture-value",
    }]).encode()
    with pytest.raises(CookieVaultError):
        vault.save("instagram", payload)


def test_cookie_import_rejects_malformed_json_without_echoing_payload(tmp_path):
    vault = CookieVault(str(tmp_path), "unit-test-key-that-is-not-a-real-secret-123")
    payload = b'{"sessionid":"do-not-echo"}'
    with pytest.raises(CookieVaultError) as error:
        vault.save("instagram", payload)
    assert "do-not-echo" not in str(error.value)


def test_netscape_cookie_comments_are_accepted_and_normalized(tmp_path):
    vault = CookieVault(str(tmp_path), "unit-test-key-that-is-not-a-real-secret-123")
    content = (
        "# Netscape HTTP Cookie File\n"
        "# generated by a browser export\n"
        ".instagram.com\tTRUE\t/\tTRUE\t1825188022\tdatr\tfixture\n"
    ).encode()
    vault.save("instagram", content)
    output = tmp_path / "cookies.txt"
    vault.load_to_file("instagram", str(output))
    assert output.read_text().count("datr") == 1
